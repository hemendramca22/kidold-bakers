export function getAllStories(): StoryArticle[] {
  return STORIES_DATA;
}

export function getStoryBySlug(slug: string): StoryArticle | undefined {
  return STORIES_DATA.find((story) => story.slug === slug);
}

export function getFeaturedStory(): StoryArticle {
  return (
    STORIES_DATA.find((s) => s.slug === "the-story-of-kidold-bakers-jaunpur-custom-celebration-cakes") ||
    STORIES_DATA.find((s) => s.featured) ||
    STORIES_DATA[0]
  );
}

export function getPopularStories(): StoryArticle[] {
  return STORIES_DATA.filter((s) => s.popular);
}

export function getLatestStories(): StoryArticle[] {
  return [...STORIES_DATA].sort(
    (a, b) => new Date(b.dateISO).getTime() - new Date(a.dateISO).getTime()
  );
}

export function getStoriesByCategory(category: StoryCategory | "All"): StoryArticle[] {
  if (category === "All") return STORIES_DATA;
  return STORIES_DATA.filter((s) => s.category === category);
}

export function getRelatedStories(currentSlug: string, count: number = 2): StoryArticle[] {
  const current = getStoryBySlug(currentSlug);
  if (!current) return STORIES_DATA.slice(0, count);

  const explicit = current.relatedSlugs
    .map((slug) => getStoryBySlug(slug))
    .filter((s): s is StoryArticle => !!s);

  if (explicit.length >= count) return explicit.slice(0, count);

  const others = STORIES_DATA.filter(
    (s) => s.slug !== currentSlug && !explicit.includes(s)
  );

  return [...explicit, ...others].slice(0, count);
}
